#!/usr/bin/env bash
# Local install for development (plan "Principles": early distribution is deliberately cheap).
# Puts a `slipbox` launcher on PATH that runs this checkout with bun, so agents and nvim
# keybindings can call it. Packaging proper is 14.x.
#
#   scripts/install-local.sh            # launcher into ~/.local/bin
#   scripts/install-local.sh --no-skill # skip the automatic skill installation for detected agents
set -euo pipefail

for arg in "$@"; do
  case "$arg" in
    --no-skill) export SLIPBOX_NO_SKILL=1 ;;
    --skill) ;; # compatibility: automatic now
    *) echo "unknown argument: $arg" >&2; exit 1 ;;
  esac
done

repo="$(cd "$(dirname "$0")/.." && pwd)"
bin_dir="${SLIPBOX_BIN_DIR:-$HOME/.local/bin}"
launcher="$bin_dir/slipbox"
mkdir -p "$bin_dir"

# A link there is removed, never written through (DF-D7): a release's installer puts its link here, to the release's
# binary, which the launcher would otherwise overwrite. The release stays installed; this file runs instead.
if [[ -L "$launcher" ]]; then
  was="$(readlink "$launcher")"
  rm -f "$launcher"
  case "$was" in
    */current/slipbox) whose="a release's, which stays installed" ;;
    *) whose="what it pointed to is left as it is" ;;
  esac
  echo "replaced the link $launcher -> $was ($whose) with this launcher"
fi

# Bun reads bunfig.toml (its preload runs) and .env from the folder it starts in, which for slipbox is
# whatever repository or notes folder you're in: slipbox's own config instead, and no .env.
cat >"$launcher" <<EOF
#!/usr/bin/env bash
# Generated by $repo/scripts/install-local.sh — runs the checkout directly.
exec bun --config="$repo/bunfig.toml" --no-env-file "$repo/src/main.ts" "\$@"
EOF
chmod +x "$launcher"
echo "installed $launcher -> $repo/src/main.ts"

case ":$PATH:" in
  *":$bin_dir:"*) ;;
  *) echo "note: $bin_dir is not on PATH in this shell" ;;
esac

"$launcher" skill --auto || echo "agent skill installation failed; the launcher is installed" >&2
