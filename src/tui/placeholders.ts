/** The most rows, and columns, a placeholder picture can say. */
export const MAX_PLACEHOLDER_CELLS = DIACRITICS.length;

const mark = (n: number) => String.fromCodePoint(DIACRITICS[n]!);

/** A picture's id: 24 bits (its colour is how its cells say it), never 0 — by its file and the cells it's drawn in. */
export function pictureId(src: string, cols: number, rows: number): number {
  let h = 0x811c9dc5;
  for (const c of `${src}\u0000${cols}x${rows}`) h = Math.imul(h ^ c.codePointAt(0)!, 0x01000193);
  return ((h >>> 0) % 0xfffffe) + 1;
}

/** The foreground colour a picture's cells are: its id. */
export function idColor(id: number): string {
  return `#${id.toString(16).padStart(6, "0")}`;
}

/** Row `row` of a picture `cols` wide, as its placeholder cells, each with its row and column marks. */
export function placeholderRow(row: number, cols: number): string {
  let out = "";
  for (let c = 0; c < cols; c++) out += PLACEHOLDER + mark(row) + mark(c);
  return out;
}

/** A placeholder cell's row and column, read from its marks; null for any other text. */
export function placeholderCell(text: string): { row: number; col: number } | null {
  const [base, row, col] = [...text].map((c) => c.codePointAt(0)!);
  if (base !== 0x10eeee || row === undefined || col === undefined) return null;
  const r = DIACRITICS.indexOf(row);
  const c = DIACRITICS.indexOf(col);
  return r < 0 || c < 0 ? null : { row: r, col: c };
}

/**
 * A picture sent: its RGBA pixels, compressed, in chunks, with a virtual placement `cols` by `rows` cells — quietly
 * (`q=2`: the terminal answers nothing, which would read as keys).
 */
export function transmit(
  id: number,
  rgba: Uint8Array,
  width: number,
  height: number,
  cols: number,
  rows: number,
): string {
  const data = Buffer.from(deflateSync(rgba)).toString("base64");
  const chunks: string[] = [];
  for (let at = 0; at < data.length; at += 4096) chunks.push(data.slice(at, at + 4096));
  return chunks
    .map((chunk, k) => {
      const more = k < chunks.length - 1 ? 1 : 0;
      const keys =
        k === 0 ? `a=T,U=1,f=32,o=z,s=${width},v=${height},i=${id},c=${cols},r=${rows},q=2,m=${more}` : `m=${more},q=2`;
      return `\x1b_G${keys};${chunk}\x1b\\`;
    })
    .join("");
}

/** A picture let go: its data, and its placements, freed in the terminal. */
export function release(id: number): string {
  return `\x1b_Ga=d,d=I,i=${id},q=2\x1b\\`;
}
